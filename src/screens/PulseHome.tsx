import { useState } from 'react'
import { Award, Bot, Hash, Sparkles, Wand2 } from 'lucide-react'
import { AGENTS, CALENDAR_EVENTS, CHANNELS, DIRECT_MESSAGES, KUDOS, LEADS, TASKS } from '../data/mockData'
import { useAppState } from '../state/appContext'
import { formatRupees, toDateKey } from '../lib/format'
import { Avatar } from '../components/ui'

const KIND_LABEL = { custom: 'Custom agent', role: 'Role agent', task: 'Task agent' }

export default function PulseHome() {
  const { openChannel, recentCalls, completedTasks, needsInputAnswers, messagesFor } = useAppState()
  const [briefOpen, setBriefOpen] = useState(false)

  // The "daily brief" is computed from local data, not generated by an AI model.
  const missed = recentCalls.filter((c) => c.direction === 'missed')
  const missedValue = missed.reduce((sum, c) => {
    const lead = LEADS.find((l) => l.id === c.leadId)
    return sum + (lead ? Math.round((lead.price * lead.intent) / 100) : 0)
  }, 0)
  const openTasks = TASKS.filter((t) => !completedTasks.includes(t.id)).length
  const todayKey = toDateKey(new Date())
  const nextEvent = CALENDAR_EVENTS.filter((e) => e.date >= todayKey).sort((a, b) => a.date.localeCompare(b.date))[0]
  const pendingInputs = CHANNELS.filter((c) => c.needsInput && !needsInputAnswers[c.id])

  return (
    <div className="page">
      <section className="avani-hero">
        <div className="avani-head">
          <span className="avani-icon"><Sparkles size={20} /></span>
          <div>
            <div className="avani-title">AvaniBot <span className="always-on">Always on</span></div>
            <div className="avani-sub">Daily briefs, action items and quick answers about what’s happening in Pulse.</div>
          </div>
        </div>
        <div className="btn-row">
          <button className="btn btn-light" onClick={() => setBriefOpen(!briefOpen)} aria-expanded={briefOpen}>
            <Wand2 size={15} /> {briefOpen ? 'Hide daily brief' : 'Daily brief'}
          </button>
          {pendingInputs[0] && (
            <button className="btn btn-outline-light" onClick={() => openChannel(pendingInputs[0].id)}>
              {pendingInputs.length} item needs your input
            </button>
          )}
        </div>
        {briefOpen && (
          <ul className="brief">
            <li>{missed.length} missed calls on record, worth about {formatRupees(missedValue)} in expected value.</li>
            <li>{openTasks} open tasks on your dashboard.</li>
            {nextEvent && <li>Next on your calendar: {nextEvent.title} at {nextEvent.time}.</li>}
            <li>{pendingInputs.length === 0 ? 'No channels are waiting on you.' : `#${pendingInputs[0].name} is waiting on your answer.`}</li>
            <li className="brief-note">Built from your local demo data. No AI model was called.</li>
          </ul>
        )}
      </section>

      <div className="pulse-grid">
        <section className="card">
          <div className="card-head"><h2><Bot size={16} /> Agents</h2></div>
          {AGENTS.map((a) => (
            <div key={a.id} className="agent-row">
              <span className={`agent-icon kind-${a.kind}`}><Bot size={16} /></span>
              <div>
                <div className="agent-name">{a.name} <span className="kind-tag">{KIND_LABEL[a.kind]}</span></div>
                <div className="muted small">{a.description}</div>
              </div>
            </div>
          ))}
        </section>

        <section className="card">
          <div className="card-head"><h2><Hash size={16} /> Channels</h2></div>
          {CHANNELS.map((c) => {
            const msgs = messagesFor(c.id)
            const last = msgs[msgs.length - 1]
            const waiting = c.needsInput && !needsInputAnswers[c.id]
            return (
              <button key={c.id} className="channel-row" onClick={() => openChannel(c.id)}>
                <Hash size={16} className="muted" />
                <div className="channel-main">
                  <div className="channel-name">{c.name}</div>
                  <div className="muted small ellipsis">{last ? `${last.author.split(' ')[0]}: ${last.text}` : c.topic}</div>
                </div>
                <div className="channel-meta">
                  <span className="muted small">{last?.sentAt}</span>
                  {waiting && <span className="needs-dot">Input</span>}
                </div>
              </button>
            )
          })}
        </section>

        <section className="card">
          <div className="card-head">
            <h2><Award size={16} /> Kudos</h2>
            <span className="count-badge">{KUDOS.length} new</span>
          </div>
          {KUDOS.map((k) => (
            <blockquote key={k.id} className="kudos">
              “{k.text}”
              <footer className="muted small">{k.from} · {k.when}</footer>
            </blockquote>
          ))}
        </section>

        <section className="card">
          <div className="card-head"><h2>Direct messages</h2></div>
          {DIRECT_MESSAGES.map((dm) => (
            <div key={dm.id} className="dm-row">
              <Avatar initials={dm.initials} size={34} tone="purple" />
              <div className="channel-main">
                <div className="channel-name">
                  {dm.name} {dm.role && <span className="kind-tag">{dm.role}</span>}
                </div>
                <div className="muted small ellipsis">{dm.preview}</div>
              </div>
              <span className="muted small">{dm.time}</span>
            </div>
          ))}
        </section>
      </div>
    </div>
  )
}
